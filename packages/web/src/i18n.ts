const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, 'zh-Hant': zhHant };

let current: Lang = 'en';

export function setLang(lang: Lang): void {
  current = lang;
}
export function getLang(): Lang {
  return current;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  let s = dictionaries[current][key] ?? en[key];
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Apply translations to every element carrying data-i18n / data-i18n-title / data-i18n-aria. */
export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as MessageKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle as MessageKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria as MessageKey));
  });
  document.documentElement.lang = current === 'zh-Hant' ? 'zh-Hant' : 'en';
}
